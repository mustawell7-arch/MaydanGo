export type MessageKey = keyof typeof messages.en | keyof typeof extra.en;

export function translate(language: Language, key: MessageKey): string {
  const base = messages[language] as Record<string, string>;
  const more = extra[language] as Record<string, string>;
  return base[key] ?? more[key] ?? (messages.en as Record<string, string>)[key] ?? (extra.en as Record<string, string>)[key] ?? key;
}

