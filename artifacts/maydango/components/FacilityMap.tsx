import React, { useCallback, useEffect, useMemo } from 'react';
import { Platform, StyleSheet, View } from 'react-native';
import { WebView, type WebViewMessageEvent } from 'react-native-webview';
import type { Coordinates } from '@/lib/location';

export type FacilityMapPoint = Coordinates & { id: string };

type Props = {
  points: FacilityMapPoint[];
  userLocation?: Coordinates | null;
  onSelect: (id: string) => void;
  title: string;
};

function buildMapHtml(points: FacilityMapPoint[], userLocation?: Coordinates | null) {
  const markerData = JSON.stringify(points.map((point, index) => ({
    index,
    latitude: point.latitude,
    longitude: point.longitude,
  }))).replace(/</g, '\\u003c');
  const userPoint = userLocation
    ? JSON.stringify([userLocation.latitude, userLocation.longitude])
    : 'null';
  return `<!DOCTYPE html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1">
<link rel="stylesheet" href="https://unpkg.com/leaflet@1.9.4/dist/leaflet.css">
<style>html,body,#map{height:100%;width:100%;margin:0;background:#f4f3ed}.leaflet-container{font:14px sans-serif}.leaflet-control-attribution{font-size:10px!important}</style>
</head><body><div id="map" aria-label="Facility map"></div>
<script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js"></script>
<script>
const points=${markerData};
const userPoint=${userPoint};
const map=L.map('map',{zoomControl:true,scrollWheelZoom:false}).setView([33.3,44.4],6);
L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png',{
  maxZoom:19,
  attribution:'&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap contributors</a>'
}).addTo(map);
const bounds=[];
function selectPoint(index){
  const payload=JSON.stringify({type:'select',index});
  if(window.ReactNativeWebView){window.ReactNativeWebView.postMessage(payload);}
  else if(window.parent){window.parent.postMessage(payload,'*');}
}
points.forEach(point=>{
  const marker=L.marker([point.latitude,point.longitude]).addTo(map);
  marker.on('click',()=>selectPoint(point.index));
  bounds.push([point.latitude,point.longitude]);
});
if(userPoint){
  L.circleMarker(userPoint,{radius:8,color:'#fff',weight:3,fillColor:'#2278d4',fillOpacity:1}).addTo(map);
  bounds.push(userPoint);
}
if(bounds.length>1){map.fitBounds(bounds,{padding:[26,26],maxZoom:14});}
else if(bounds.length===1){map.setView(bounds[0],14);}
</script></body></html>`;
}

export function FacilityMap({ points, userLocation, onSelect, title }: Props) {
  const html = useMemo(() => buildMapHtml(points, userLocation), [points, userLocation]);

  const handleMessage = useCallback((raw: string) => {
    try {
      const message = JSON.parse(raw) as { type?: string; index?: number };
      if (message.type !== 'select' || !Number.isInteger(message.index)) return;
      const point = points[message.index as number];
      if (point) onSelect(point.id);
    } catch {
      // Ignore messages that are not generated by a map marker tap.
    }
  }, [onSelect, points]);

  const onNativeMessage = useCallback((event: WebViewMessageEvent) => {
    handleMessage(event.nativeEvent.data);
  }, [handleMessage]);

  useEffect(() => {
    if (Platform.OS !== 'web' || typeof window === 'undefined') return;
    const onWebMessage = (event: MessageEvent) => {
      if (typeof event.data === 'string') handleMessage(event.data);
    };
    window.addEventListener('message', onWebMessage);
    return () => window.removeEventListener('message', onWebMessage);
  }, [handleMessage]);

  return (
    <View style={styles.container}>
      {Platform.OS === 'web'
        ? React.createElement('iframe' as React.ElementType, {
            title,
            srcDoc: html,
            referrerPolicy: 'no-referrer',
            style: { width: '100%', height: '100%', border: 0 },
          })
        : <WebView
            accessibilityLabel={title}
            originWhitelist={['https://*']}
            source={{ html, baseUrl: 'https://www.openstreetmap.org' }}
            javaScriptEnabled
            domStorageEnabled={false}
            scrollEnabled={false}
            setSupportMultipleWindows={false}
            onMessage={onNativeMessage}
            style={styles.webview}
          />}
    </View>
  );
}

const styles = StyleSheet.create({
  container: { height: 350, width: '100%', overflow: 'hidden', borderRadius: 18, backgroundColor: '#f4f3ed' },
  webview: { flex: 1, backgroundColor: '#f4f3ed' },
});
